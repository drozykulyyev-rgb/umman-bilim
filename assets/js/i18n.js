  const dict = {};
  rows.split("\n").forEach((r) => {
    let [ru, tk, en] = r.split("|");
    dict[ru] = { ru, tk, en };
    if (ru === ru.toLowerCase() || !ru) return;
    dict[ru.toUpperCase()] = {
      ru: ru.toUpperCase(),
      tk: tk.toUpperCase(),
      en: en.toUpperCase(),
    };
  });
  for (let i = 1; i <= 12; i++)
    dict[i + " класс"] = {
      ru: i + " класс",
      tk: i + "-nji synp",
      en: "Grade " + i,
    };
  let lang = localStorage.getItem("umman-language") || "ru";
  if (!["ru", "tk", "en"].includes(lang)) lang = "ru";
  const originals = new WeakMap();
  function translate(s) {
    if (dict[s]) return dict[s][lang];
    return s;
  }
  const originalTitle = document.title;
  function apply() {
    document.title = translate(originalTitle);
    document.documentElement.lang = lang;
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    let n;
    while ((n = walker.nextNode())) {
      if (
        ["SCRIPT", "STYLE"].includes(n.parentElement.tagName) ||
        n.parentElement.closest("[data-native]")
      )
        continue;
      let src = originals.get(n);
      if (src === undefined) {
        src = n.nodeValue;
        originals.set(n, src);
      }
      const trim = src.trim();
      if (dict[trim]) n.nodeValue = src.replace(trim, translate(trim));
    }
    document.querySelectorAll("[placeholder]").forEach((el) => {
      el.dataset.ruPlaceholder ??= el.placeholder;
      el.placeholder = translate(el.dataset.ruPlaceholder);
    });
    document
      .querySelectorAll(".langs button")
      .forEach((b) =>
        b.classList.toggle(
          "active",
          (b.textContent.trim() === "TM"
            ? "tk"
            : b.textContent.toLowerCase().trim()) === lang,
        ),
      );
    document.title = document.title
      .replace(/Курсы|Kurslar|Courses/g, translate("Курсы"))
      .replace(
        /Запись на курс|Kursa ýazylmak|Enrol in a course/g,
        translate("Запись на курс"),
      );
  }
  document.querySelectorAll(".langs button").forEach(
    (b) =>
      (b.onclick = () => {
        lang =
          b.textContent.trim() === "TM"
            ? "tk"
            : b.textContent.toLowerCase().trim();
        localStorage.setItem("umman-language", lang);
        apply();
        window.dispatchEvent(new Event("languagechange"));
      }),
  );
  window.umman = {
    t: translate,
    apply,
    get lang() {
      return lang;
    },
  };
  apply();
